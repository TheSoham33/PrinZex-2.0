/**
 * FCM messaging service worker (gap #10).
 *
 * Shows push notifications while the app is closed/backgrounded. The Firebase
 * *web* config below is PUBLIC by design (apiKey is not a secret). It is a
 * placeholder — regenerate this file for your project with:
 *
 *   NEXT_PUBLIC_FIREBASE_CONFIG='{"apiKey":"…","authDomain":"…","projectId":"…","messagingSenderId":"…","appId":"…"}' \
 *   npx tsx scripts/generate-firebase-sw.ts
 *
 * (the generator rewrites only the FIREBASE_CONFIG object; the handler below
 * is preserved verbatim). Keep the two SDK versions in sync with
 * frontend/package.json `firebase`.
 */

/* eslint-disable */
importScripts('https://www.gstatic.com/firebasejs/12.19.0/firebase-app-compat.js');
importScripts('https://www.gstatic.com/firebasejs/12.19.0/firebase-messaging-compat.js');

// __FIREBASE_CONFIG_START__ (regenerated by scripts/generate-firebase-sw.ts)
const FIREBASE_CONFIG = {
  apiKey: '',
  authDomain: '',
  projectId: '',
  messagingSenderId: '',
  appId: '',
};
// __FIREBASE_CONFIG_END__

const configured = FIREBASE_CONFIG.apiKey && FIREBASE_CONFIG.projectId && FIREBASE_CONFIG.messagingSenderId && FIREBASE_CONFIG.appId;

if (configured) {
  firebase.initializeApp(FIREBASE_CONFIG);
  const messaging = firebase.messaging();

  messaging.onBackgroundMessage((payload) => {
    const title = payload.notification?.title || payload.data?.title || 'PrinZex';
    const body = payload.notification?.body || payload.data?.body || '';
    const tag = payload.data?.type || 'prinzex-notification';

    const notificationOptions = {
      body,
      tag,
      // No icon asset ships in the repo yet — the browser falls back to its
      // default. Drop an icon in public/ and reference it here to brand it.
      data: payload.data || {},
      requireInteraction: false,
    };

    self.registration.showNotification(title, notificationOptions);
  });

  self.addEventListener('notificationclick', (event) => {
    event.notification.close();
    const data = event.notification.data || {};
    let target = '/';
    if (data.orderId) target = `/dashboard/orders/${data.orderId}`;

    event.waitUntil(
      self.clients.matchAll({ type: 'window', includeUncontrolled: true }).then((windowClients) => {
        for (const client of windowClients) {
          if ('focus' in client) return client.focus();
        }
        if (self.clients.openWindow) return self.clients.openWindow(target);
        return undefined;
      }),
    );
  });
}
